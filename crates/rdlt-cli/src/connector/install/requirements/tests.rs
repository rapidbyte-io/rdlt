/// The characters Python's `str.splitlines`, which pip reads a requirements file with, ends a line
/// at, but for `\n`.
const BREAKS: [char; 9] = [
    '\r', '\u{b}', '\u{c}', '\u{1c}', '\u{1d}', '\u{1e}', '\u{85}', '\u{2028}', '\u{2029}',
];

/// `text` broken into lines as Python's `str.splitlines` breaks it.
fn python_lines(text: &str) -> Vec<String> {
    let text = text.replace("\r\n", "\n");
    text.split(|c| c == '\n' || BREAKS.contains(&c))
        .map(str::to_owned)
        .collect()
}

#[test]
fn a_character_that_could_end_a_line_for_pip_is_refused_in_markers_options_and_comments() {
    let hash = format!("--hash=sha256:{HEX}");
    for break_ in BREAKS {
        for line in [
            format!("ok==1.0 ; python_version>\"0\"{break_}--no-binary :all: {hash}"),
            format!("--find-links https://example.com/ok{break_}-1.0-py3-none-any.whl"),
            format!("# a note{break_}--no-binary :all:\nok==1.0 {hash}"),
        ] {
            let found = checked(&line, Path::new("/requirements"));
            assert_eq!(found, Err((1, Refused::Character(break_))), "{line:?}");
        }
    }
    for refused in ['\u{0}', '\u{7f}', 'é', '\u{feff}'] {
        let line = format!("ok==1.0 {hash}\nother==1.0 ; os_name == 'x{refused}' {hash}");
        let found = checked(&line, Path::new("/requirements"));
        assert_eq!(found, Err((2, Refused::Character(refused))), "{line:?}");
    }
}


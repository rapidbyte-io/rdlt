/// A few hundred requirement lines rdlt's grammar takes, drawn across its names, extras,
/// versions, markers and hashes.
fn generated() -> String {
    const NAMES: [&str; 6] = ["a", "pkg", "Pkg_Name", "pkg.name", "pkg-name", "x1"];
    const EXTRAS: [&str; 3] = ["", "[e]", "[e1, e_2]"];
    const VERSIONS: [&str; 13] = [
        "1",
        "1.0",
        "2.11.7",
        "1!2.0",
        "v1.0",
        "1.0a1",
        "1.0rc2",
        "1.0.post1",
        "1.0.dev3",
        "1.0+local.7",
        "1.0-1",
        "2024.1.POST1",
        "1.0+x.y",
    ];
    const MARKERS: [&str; 6] = [
        "",
        " ; os_name == 'nt'",
        " ; python_version >= '3.11' and sys_platform != \"win32\"",
        " ; (os_name == 'posix' or os_name == 'nt') and extra == 'a,b'",
        " ; 'linux' in sys_platform",
        " ; python_version not in '3.1*'",
    ];
    let hashes = [
        format!("--hash=sha256:{HEX}"),
        format!("--hash=sha256:{HEX} --hash=sha512:{HEX}{HEX}"),
        format!("--hash sha384:{HEX}{}", &HEX[..32]),
    ];
    let mut text = String::new();
    for i in 0..300 {
        writeln!(
            text,
            "{}{} == {}{} {}",
            NAMES[i % NAMES.len()],
            EXTRAS[(i / NAMES.len()) % EXTRAS.len()],
            VERSIONS[(i * 7) % VERSIONS.len()],
            MARKERS[(i * 5) % MARKERS.len()],
            hashes[(i * 11) % hashes.len()]
        )
        .unwrap();
    }
    text
}

/// The hashes `hashes` names, by algorithm, as pip keeps them.
fn by_algorithm(hashes: &[String]) -> serde_json::Value {
    let mut kept: BTreeMap<&str, Vec<&str>> = BTreeMap::new();
    for hash in hashes {
        let (algorithm, hex) = hash.split_once(':').unwrap();
        kept.entry(algorithm).or_default().push(hex);
    }
    serde_json::json!({ "hashes": kept })
}

/// Asserts that pip, reading `line`, the written form of what rdlt read, `read`, reads what rdlt
/// checked; `said` is what the oracle saw.
fn read_alike(read: &Line, line: &str, said: &serde_json::Value) {
    let context = format!("{line:?}: {said}");
    assert_eq!(said["no_binary"], serde_json::json!([]), "{context}");
    assert_eq!(said["only_binary"], serde_json::json!([]), "{context}");
    match read {
        Line::Pinned(pinned) => {
            assert_eq!(said["args"], pinned.requirement(), "{context}");
            let options: Vec<String> = pinned
                .hashes
                .iter()
                .map(|hash| format!("--hash={hash}"))
                .collect();
            assert_eq!(said["options"], serde_json::json!(options), "{context}");
            let mut extras = pinned.extras.clone();
            extras.sort();
            let expected = serde_json::json!([{
                "name": pinned.name,
                "extras": extras,
                "specifier": format!("=={}", pinned.version),
                "url": null,
                "marked": pinned.markers.is_some(),
                "link": null,
                "wheel": null,
                "file": null,
                "options": by_algorithm(&pinned.hashes),
            }]);
            assert_eq!(said["requirements"], expected, "{context}");
        }
        Line::Place { option, value } => {
            assert_eq!(said["requirements"], serde_json::json!([]), "{context}");
            let (links, indexes) = if *option == "--find-links" {
                (vec![value], vec![])
            } else {
                (vec![], vec![value])
            };
            assert_eq!(said["find_links"], serde_json::json!(links), "{context}");
            assert_eq!(said["index_urls"], serde_json::json!(indexes), "{context}");
        }
        Line::NoIndex => {
            assert_eq!(said["requirements"], serde_json::json!([]), "{context}");
            assert_eq!(said["no_index"], true, "{context}");
        }
    }
}

/// What pip, as an install runs it, reads of each of `lines`, by the oracle's script; none where
/// no interpreter of the system's is here.
fn read_by_pip(lines: &[String]) -> Option<Vec<serde_json::Value>> {
    let python = system_python()?;
    let dir = tempfile::tempdir().unwrap();
    // pip as an install runs it: what the interpreter carries, in an environment of its own.
    let installer = dir.path().join("installer");
    let made = std::process::Command::new(&python)
        .args(["-I", "-m", "venv"])
        .arg(&installer)
        .status()
        .unwrap();
    assert!(made.success(), "the environment pip runs from is made");
    let cases = dir.path().join("lines.json");
    std::fs::write(&cases, serde_json::to_string(lines).unwrap()).unwrap();
    // Where pip runs in an install: a directory of the install's own, holding nothing else.
    let (work, running) = (dir.path().join("work"), dir.path().join("running"));
    std::fs::create_dir(&work).unwrap();
    std::fs::create_dir(&running).unwrap();
    let output = std::process::Command::new(installer.join("bin/python"))
        .args(["-I", "-c", include_str!("oracle.py")])
        .arg(&cases)
        .arg(&work)
        .current_dir(&running)
        .env("PIP_CONFIG_FILE", "/dev/null")
        .output()
        .unwrap();
    assert!(output.status.success(), "{output:?}");
    let said: Vec<serde_json::Value> = serde_json::from_slice(&output.stdout).unwrap();
    assert_eq!(said.len(), lines.len());
    Some(said)
}

/// What pip reads of the wheel's line, the copy at `held` of the distribution `name` named by
/// `referenced`, where pip reads it as that wheel's URL.
fn read_as_the_wheel(name: &str, held: &Path, referenced: &str) -> serde_json::Value {
    let uri = referenced.split_once(" @ ").unwrap().1;
    serde_json::json!({
        "args": referenced,
        "options": [format!("--hash=sha256:{HEX}")],
        "requirements": [{
            "name": name,
            "extras": [],
            "specifier": "",
            "url": uri,
            "marked": false,
            "link": uri,
            "wheel": true,
            "file": held.to_str().unwrap(),
            "options": { "hashes": { "sha256": [HEX] } },
        }],
        "find_links": [],
        "index_urls": [],
        "no_index": false,
        "no_binary": [],
        "only_binary": [],
    })
}

